def detect_language():
    try:
        import locale
        loc = locale.getdefaultlocale()[0] or "pt"
    except Exception:
        loc = "pt"
    loc = str(loc).lower()
    if loc.startswith("es"):
        return "es"
    if loc.startswith("en"):
        return "en"
    return "pt"


